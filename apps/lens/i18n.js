  var SUPPORTED_LOCALES = ["en", "nl", "de", "fr"];
  var DEFAULT_LOCALE = "en";
  var LOCALE_STORAGE_KEY = "wt_locale";
  var LOCALE_LABELS = {
    en: "English",
    nl: "Nederlands",
    de: "Deutsch",
    fr: "Fran\xE7ais"
  };
  var localeInputs = { en: en_default, nl: nl_default, de: de_default, fr: fr_default };
  function mergeCatalog(primary, fallback) {
    return {
      fields: { ...fallback.fields, ...primary.fields },
      tier: { ...fallback.tier, ...primary.tier },
      source: { ...fallback.source, ...primary.source },
      roomTypes: { ...fallback.roomTypes, ...primary.roomTypes },
      photoSlots: { ...fallback.photoSlots, ...primary.photoSlots },
      ui: { ...fallback.ui, ...primary.ui }
    };
  }
  function getCatalog(locale) {
    const loc = locale;
    const primary = localeInputs[loc];
    if (!primary || loc === "en") return en_default;
    return mergeCatalog(primary, en_default);
  }
  function resolveLocale(options = {}) {
    const { stored, acceptLanguage, nodeDefault } = options;
    if (stored && isSupportedLocale(stored)) return stored;
    if (acceptLanguage) {
      const preferred = parseAcceptLanguage(acceptLanguage);
      if (preferred) return preferred;
    }
    if (nodeDefault && isSupportedLocale(nodeDefault)) return nodeDefault;
    return DEFAULT_LOCALE;
  }
  function isSupportedLocale(value) {
    return SUPPORTED_LOCALES.includes(value);
  }
  function parseAcceptLanguage(header) {
    const parts = header.split(",").map((p) => p.trim().split(";")[0]?.toLowerCase());
    for (const part of parts) {
      if (!part) continue;
      if (isSupportedLocale(part)) return part;
      const base = part.split("-")[0];
      if (base && isSupportedLocale(base)) return base;
    }
    return null;
  }
  function t(key, locale = DEFAULT_LOCALE, params) {
    const catalog = getCatalog(locale);
    const parts = key.split(".");
    let current = catalog;
    for (const part of parts) {
      if (current == null || typeof current !== "object") return key;
      current = current[part];
    }
    if (typeof current !== "string") return key;
    if (!params) return current;
    return current.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`));
  }
  function getFieldLabel(fieldName, locale = DEFAULT_LOCALE) {
    const label = getCatalog(locale).fields[fieldName];
    if (label) return label;
    return fieldName.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
  }
  function getTierLabel(tier, locale = DEFAULT_LOCALE) {
    return getCatalog(locale).tier[tier] ?? tier;
  }
